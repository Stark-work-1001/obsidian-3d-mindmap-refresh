// Regenerate licenses/rust-crates.txt from Cargo.lock and the local Cargo
// registry (development tool; run after changing Rust dependencies).
//   node scripts/rust-licenses.mjs
// Every crate in Cargo.lock except our own is listed with its MIT licence text
// (or its only licence file); the release bundle embeds this file.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const lock = fs.readFileSync(path.join(root, 'Cargo.lock'), 'utf8');
const crates = [...lock.matchAll(/\[\[package\]\]\nname = "([^"]+)"\nversion = "([^"]+)"\n(source = "registry[^"]*")?/g)]
  .filter(m => m[3]).map(m => ({ name: m[1], version: m[2] }));
const registry = path.join(process.env.CARGO_HOME ?? path.join(os.homedir(), '.cargo'), 'registry', 'src');
const indexes = fs.existsSync(registry) ? fs.readdirSync(registry).map(d => path.join(registry, d)) : [];
const out = ['Third-party Rust crates compiled into the physics WebAssembly module or used to build it.', 'Generated by scripts/rust-licenses.mjs from Cargo.lock.', ''];
const missing = [];
for (const { name, version } of crates) {
  const dir = indexes.map(i => path.join(i, `${name}-${version}`)).find(d => fs.existsSync(d));
  const file = dir && ['LICENSE-MIT', 'LICENSE-MIT.md', 'LICENSE', 'LICENSE.md', 'LICENSE.txt'].map(f => path.join(dir, f)).find(f => fs.existsSync(f));
  if (!file) { missing.push(`${name} ${version}`); continue; }
  out.push('='.repeat(78), `${name} ${version} (${path.basename(file)})`, '='.repeat(78), fs.readFileSync(file, 'utf8').trim(), '');
}
if (missing.length) { console.error(`licence text not found for: ${missing.join(', ')} (run cargo fetch first)`); process.exit(1); }
fs.writeFileSync(path.join(root, 'licenses', 'rust-crates.txt'), out.join('\n') + '\n');
console.log(`wrote licenses/rust-crates.txt (${crates.length} crates)`);
